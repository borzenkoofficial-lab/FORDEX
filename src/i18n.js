export function ruDate(value) {
  if (!value) return value;
  return String(value)
    .replaceAll('JAN', 'ЯНВ')
    .replaceAll('FEB', 'ФЕВ')
    .replaceAll('MAR', 'МАР')
    .replaceAll('APR', 'АПР')
    .replaceAll('MAY', 'МАЙ')
    .replaceAll('JUN', 'ИЮН')
    .replaceAll('JUL', 'ИЮЛ')
    .replaceAll('AUG', 'АВГ')
    .replaceAll('SEP', 'СЕН')
    .replaceAll('OCT', 'ОКТ')
    .replaceAll('NOV', 'НОЯ')
    .replaceAll('DEC', 'ДЕК');
}
